import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { schema, limits } from '../src/shared/protocol/schema-source.mjs';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
function type(node) {
  if (node.$ref) return node.$ref.split('/').at(-1);
  if (node.oneOf) return node.oneOf.map(type).join(' | ');
  if ('const' in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(v => JSON.stringify(v)).join(' | ');
  if (node.type === 'object') return `{ ${Object.entries(node.properties).map(([key, value]) => `${key}${node.required.includes(key) ? '' : '?'}: ${type(value)}`).join('; ')} }`;
  if (node.type === 'array') return `Array<${type(node.items)}>`;
  if (node.type === 'integer' || node.type === 'number') return 'number';
  return node.type;
}
const header = '// Generated by scripts/generate-protocol.mjs; edit schema-source.mjs instead.\n';
const types = header + `export const PROTOCOL_VERSION = 1 as const;\nexport const LIMITS = ${JSON.stringify(limits)} as const;\n\n` + Object.entries(schema.$defs).map(([name, def]) => `export type ${name} = ${type(def)};`).join('\n\n') + `\n\nexport type WireMessage = ${type(schema)};\n`;
const json = JSON.stringify(schema, null, 2) + '\n';
if (json.includes('"""#')) {
  throw new Error('Wire schema JSON contains Swift raw-string delimiter """#');
}
const swiftSchema = [
  '// Generated by scripts/generate-protocol.mjs; edit schema-source.mjs instead.',
  'import Foundation',
  '',
  'enum GeneratedWireSchema {',
  '    static let json = #"""',
  json.trimEnd(),
  '"""#',
  '',
  '    static let utf8Data = Data(json.utf8)',
  '}',
  '',
].join('\n');
const output = [
  ['src/shared/protocol/wire.schema.json', json],
  ['src/shared/protocol/generated.ts', types],
  ['native/macos/Sources/HistoryContract/GeneratedWireSchema.swift', swiftSchema],
];
let changed = false;
for (const [relative, content] of output) {
  const path = fileURLToPath(new URL(relative, root));
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
  if (current === content) continue;
  if (check) { console.error(`Generated artifact out of date: ${relative}`); changed = true; continue; }
  // Only the three enumerated generated artifacts above are replaced.
  mkdirSync(fileURLToPath(new URL('./', new URL(relative, root))), { recursive: true });
  writeFileSync(path, content, { mode: 0o600 });
  console.log(`Generated ${relative}`);
}
if (changed) process.exitCode = 1;
else console.log(check ? 'Generated protocol artifacts are current.' : 'Protocol generation complete.');
